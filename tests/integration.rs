/// The headline fix: a plain coding session (repeated file reads + a failed
/// Bash, NO browser tools, NO screenshots) is now pruned out of the box by the
/// default-on cross_turn_dedup + failed_input_purge — previously inert.
#[tokio::test]
async fn gateway_prunes_a_plain_coding_session() {
    let upstream = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/v1/messages"))
        .respond_with(ResponseTemplate::new(200).set_body_bytes(b"ok".to_vec()))
        .mount(&upstream)
        .await;

    // Build a coding session: one old failed Bash, then 6 identical Reads.
    let mut messages = vec![
        json_msg("user", "fix the bug"),
        json!({"role": "assistant", "content": [
            {"type": "tool_use", "id": "u_bash", "name": "Bash",
             "input": {"command": "cargo test --some-very-long-flag-that-failed"}}
        ]}),
        json!({"role": "user", "content": [
            {"type": "tool_result", "tool_use_id": "u_bash", "is_error": true,
             "content": "error: no such flag"}
        ]}),
    ];
    let big = "x".repeat(4000); // a chunky file each read re-sends
    for i in 0..6 {
        let uid = format!("u_read{i}");
        messages.push(json_msg("user", "read it again"));
        messages.push(json!({"role": "assistant", "content": [
            {"type": "tool_use", "id": uid, "name": "Read", "input": {"path": "/src/lib.rs"}}
        ]}));
        messages.push(json!({"role": "user", "content": [
            {"type": "tool_result", "tool_use_id": uid, "content": big.clone()}
        ]}));
    }
    let body_in = serde_json::to_vec(&json!({"model": "claude", "messages": messages})).unwrap();

    // Default-style config: the two workhorse strategies on; no browser/image.
    let mut config = Config::default();
    config.strategies.cross_turn_dedup.enabled = true;
    config.strategies.failed_input_purge.enabled = true;

    let (listener, gw_addr) = bind_listener().await;
    let upstream_uri = upstream.uri();
    tokio::spawn(async move {
        let _ = gateway::run_from_listener(
            listener,
            upstream_uri,
            Arc::new(config),
            Ledger::disabled(),
            None,
        )
        .await;
    });
    await_listening(gw_addr).await;

    let client = reqwest::Client::builder().build().expect("client");
    let res = client
        .post(format!("http://{gw_addr}/v1/messages"))
        .header("content-type", "application/json")
        .body(body_in.clone())
        .send()
        .await
        .expect("send");
    assert_eq!(res.status().as_u16(), 200);

    let received = await_received(&upstream, 1).await;
    let fwd = &received[0].body;
    assert!(
        fwd.len() < body_in.len() / 2,
        "coding session should shrink a lot: {} -> {}",
        body_in.len(),
        fwd.len()
    );
    let fwd_body: Value = serde_json::from_slice(fwd).unwrap();
    let messages = fwd_body["messages"].as_array().unwrap();
    // 5 of the 6 identical reads superseded; the failed Bash input cleared.
    let superseded = serde_json::to_string(messages)
        .unwrap()
        .matches("superseded by a later identical call")
        .count();
    assert_eq!(superseded, 5, "5 older identical reads deduped");
    // Shape-preserving purge: the small failed command is kept (the model still
    // sees what failed) — only bulk would be elided.
    assert_eq!(
        messages[1]["content"][0]["input"]["command"],
        json!("cargo test --some-very-long-flag-that-failed"),
        "failed Bash command kept"
    );
    PairingIndex::build(messages)
        .validate()
        .expect("no orphans");
}

/// Small helper for a plain text user/assistant message.
fn json_msg(role: &str, text: &str) -> Value {
    json!({"role": role, "content": [{"type": "text", "text": text}]})
}

/// The headline contract: the SSE response is **streamed**, not buffered. A
/// raw upstream sends one chunk, waits, sends another, then closes — so a
/// streaming proxy delivers the first chunk long before the second, while a
/// buffering one would deliver both at once. Guards against a future refactor
/// (or hyper bump) that silently starts buffering `text/event-stream`.
#[tokio::test]
async fn sse_response_streams_incrementally_not_buffered() {
    use tokio::io::{AsyncReadExt, AsyncWriteExt};

    const DELAY: Duration = Duration::from_millis(400);

    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let up_addr = listener.local_addr().unwrap();
    tokio::spawn(async move {
        if let Ok((mut sock, _)) = listener.accept().await {
            let mut buf = [0u8; 2048];
            let _ = sock.read(&mut buf).await; // drain request headers
            let head = b"HTTP/1.1 200 OK\r\ncontent-type: text/event-stream\r\ntransfer-encoding: chunked\r\n\r\n";
            let _ = sock.write_all(head).await;
            let _ = sock.write_all(b"b\r\ndata: one\n\n\r\n").await; // 11-byte chunk
            let _ = sock.flush().await;
            tokio::time::sleep(DELAY).await;
            let _ = sock.write_all(b"b\r\ndata: two\n\n\r\n").await;
            let _ = sock.write_all(b"0\r\n\r\n").await; // chunked terminator
            let _ = sock.flush().await;
        }
    });

    let (listener, gw_addr) = bind_listener().await;
    let upstream_uri = format!("http://{up_addr}");
    tokio::spawn(async move {
        let _ = gateway::run_from_listener(
            listener,
            upstream_uri,
            Arc::new(Config::default()),
            Ledger::disabled(),
            None,
        )
        .await;
    });
    await_listening(gw_addr).await;

    let client = reqwest::Client::builder().build().unwrap();
    let start = std::time::Instant::now();
    let mut res = client
        .post(format!("http://{gw_addr}/v1/messages"))
        .body(br#"{"model":"claude","messages":[]}"#.to_vec())
        .send()
        .await
        .expect("send through gateway");

    // First chunk must arrive well before the upstream sent the second one.
    let first = res
        .chunk()
        .await
        .expect("read first chunk")
        .expect("first chunk has bytes");
    let t_first = start.elapsed();
    assert!(
        first.starts_with(b"data: one"),
        "unexpected first chunk: {first:?}"
    );
    assert!(
        t_first < DELAY / 2,
        "first chunk took {t_first:?} (>= {:?}) — the gateway buffered instead of streaming",
        DELAY / 2
    );

    // The second event arrives only after the upstream's delay — proving the
    // stream stayed open and forwarded incrementally rather than all at once.
    let mut saw_two = false;
    while let Some(chunk) = res.chunk().await.expect("read chunk") {
        if chunk.windows(3).any(|w| w == b"two") {
            saw_two = true;
        }
    }
    assert!(saw_two, "second SSE event never arrived");
    assert!(
        start.elapsed() >= DELAY,
        "whole response arrived in {:?} (< {DELAY:?}) — not actually streamed",
        start.elapsed()
    );
}

/// End-to-end proof that `--audit`/`TRIMWIRE_AUDIT` (threaded as the gateway's
/// `audit_path` param) writes one metadata-only JSONL line per request: the
/// right shape/counts and headers, and — the load-bearing assertion — never the
/// message content itself.
#[tokio::test]
async fn wire_audit_records_metadata_only_never_content() {
    let upstream = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/v1/messages"))
        .respond_with(ResponseTemplate::new(200).set_body_bytes(b"ok".to_vec()))
        .mount(&upstream)
        .await;

    let dir = tempfile::tempdir().expect("tempdir");
    let audit_path = dir.path().join("audit.jsonl");
    let audit_str = audit_path.to_str().expect("utf8 path").to_owned();

    let (listener, gw_addr) = bind_listener().await;
    let upstream_uri = upstream.uri();
    tokio::spawn(async move {
        let _ = gateway::run_from_listener(
            listener,
            upstream_uri,
            Arc::new(Config::default()),
            Ledger::disabled(),
            Some(audit_str),
        )
        .await;
    });
    await_listening(gw_addr).await;

    // A canary that must never appear in the audit, plus one string-content and
    // one array-content tool_result so the shape counters have something to count.
    let secret = "LEAK_CANARY_DO_NOT_RECORD";
    let body = serde_json::to_vec(&json!({
        "model": "claude-opus-4-8",
        "messages": [
            {"role": "user", "content": [
                {"type": "tool_result", "tool_use_id": "t1", "content": format!("port {secret}")}
            ]},
            {"role": "user", "content": [
                {"type": "tool_result", "tool_use_id": "t2", "content": [{"type": "text", "text": "arr"}]}
            ]},
        ]
    }))
    .expect("encode body");

    let client = reqwest::Client::builder().build().expect("client");
    let res = client
        .post(format!("http://{gw_addr}/v1/messages"))
        .header("content-type", "application/json")
        .header("x-claude-code-session-id", "sess-AUDIT")
        .header("anthropic-beta", "context-management-2025-06-27")
        .body(body)
        .send()
        .await
        .expect("send");
    assert_eq!(res.status().as_u16(), 200);

    // The audit write is synchronous (before the forward), but poll briefly to
    // stay robust to scheduling.
    let mut contents = String::new();
    for _ in 0..200 {
        if let Ok(s) = std::fs::read_to_string(&audit_path) {
            if !s.trim().is_empty() {
                contents = s;
                break;
            }
        }
        tokio::time::sleep(Duration::from_millis(10)).await;
    }
    assert!(!contents.is_empty(), "audit file never got a line");
    assert!(
        !contents.contains(secret),
        "audit must be metadata-only — leaked message content: {contents}"
    );

    let line: Value =
        serde_json::from_str(contents.lines().next().expect("one line")).expect("parse audit line");
    assert_eq!(line["session_id"], json!("sess-AUDIT"));
    assert_eq!(line["model"], json!("claude-opus-4-8"));
    assert_eq!(
        line["anthropic_beta"],
        json!("context-management-2025-06-27")
    );
    assert_eq!(line["num_tool_result_blocks"], json!(2));
    assert_eq!(line["num_string_content"], json!(1));
    assert_eq!(line["num_array_content"], json!(1));
}
