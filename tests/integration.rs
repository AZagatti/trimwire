const SW_STUB: &str = "[trimwire: elided, older than sliding window]";

/// Count tool_result blocks whose content equals the SlidingWindow stub.
fn count_stubbed(messages: &[Value]) -> usize {
    messages
        .iter()
        .filter_map(|m| m.get("content").and_then(Value::as_array))
        .flatten()
        .filter(|b| {
            b.get("content")
                .and_then(Value::as_str)
                .is_some_and(|s| s.starts_with(SW_STUB))
        })
        .count()
}

/// With SlidingWindow enabled, the body the upstream receives has old Bash
/// pairs stubbed, stays orphan-free, and is smaller than the original.
#[tokio::test]
async fn gateway_prunes_messages() {
    let upstream = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/v1/messages"))
        .respond_with(ResponseTemplate::new(200).set_body_bytes(b"ok".to_vec()))
        .mount(&upstream)
        .await;

    let (listener, gw_addr) = bind_listener().await;
    let upstream_uri = upstream.uri();
    let mut config = Config::default();
    config.strategies.sliding_window = standard_sliding_cfg();
    tokio::spawn(async move {
        let _ = gateway::run_from_listener(
            listener,
            upstream_uri,
            Arc::new(config),
            Ledger::disabled(),
            None,
        )
        .await;
    });
    await_listening(gw_addr).await;

    let body_in = load_fixture_bytes("long_session");
    let client = reqwest::Client::builder().build().expect("client");
    let res = client
        .post(format!("http://{gw_addr}/v1/messages"))
        .header("content-type", "application/json")
        .body(body_in.clone())
        .send()
        .await
        .expect("send");
    assert_eq!(res.status().as_u16(), 200);

    let received = await_received(&upstream, 1).await;
    assert_eq!(received.len(), 1);
    let fwd = &received[0].body;

    // Body shrank (old inputs -> {}, old results -> stub).
    assert!(
        fwd.len() < body_in.len(),
        "forwarded body ({}) should be smaller than original ({})",
        fwd.len(),
        body_in.len()
    );

    let fwd_body: Value = serde_json::from_slice(fwd).expect("parse forwarded");
    let messages = fwd_body["messages"].as_array().expect("messages[]");
    // 100 turns, keep 4 -> 96 stubbed.
    assert_eq!(count_stubbed(messages), 96);
    // No orphans introduced.
    PairingIndex::build(messages)
        .validate()
        .expect("forwarded body orphan-free");
    // The system field is untouched.
    assert_eq!(fwd_body["system"], body_in_json(&body_in)["system"]);
}

