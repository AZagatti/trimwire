//! Phase 1 integration tests.
//!
//! - Step 1 (pass-through gateway): stubs a fake upstream with `wiremock`,
//!   points the gateway at it, and verifies request/response byte-equality.
//! - Step 2 (pairing): loads the committed Phase 0 fixture corpus, builds the
//!   `PairingIndex`, asserts the orphan invariant, and snapshots each index
//!   with `insta`. The Rust index must match the Python reference
//!   (`tests/phase0/pairing.py`) on the same fixtures.

